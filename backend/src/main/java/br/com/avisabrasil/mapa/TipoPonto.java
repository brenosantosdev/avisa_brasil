package br.com.avisabrasil.mapa;

/** Tipos de ponto de apoio mostrados no mapa. */
public enum TipoPonto {
    /** Escolas, creches, faculdades. */
    ESCOLA,
    /** Hospitais, postos e unidades de saúde. */
    SAUDE,
    /** Prédios públicos que podem ajudar: centro comunitário, prefeitura, polícia, bombeiros. */
    APOIO,
    /** Abrigo ou ponto de encontro de emergência. */
    ABRIGO
}
